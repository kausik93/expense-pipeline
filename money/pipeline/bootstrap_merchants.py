"""Build money/config/merchants.yaml from the historical categorized tabs.

Reads every monthly tab in the expenses workbook, takes each row's
(Description, Category), reduces the description to a stable merchant key, and
majority-votes a category per key. The result is a deterministic lookup table
that is committed and hand-editable. Re-runnable: regenerates the file from
scratch. Ambiguous keys and unmappable category labels are reported so they can
be reviewed by hand.

    python money/pipeline/bootstrap_merchants.py [path/to/workbook.xlsx]
"""
from __future__ import annotations

import sys
from collections import Counter, defaultdict
from pathlib import Path
from typing import Dict, Optional

import pandas as pd
import yaml

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT))

from money.pipeline.config import CONFIG_DIR, load_categories  # noqa: E402
from money.pipeline.text import merchant_key  # noqa: E402

DEFAULT_WORKBOOK = ROOT / "money" / "sample_data" / "expenses_history.xlsx"
OUT_PATH = CONFIG_DIR / "merchants.yaml"
REPORT_PATH = CONFIG_DIR / "merchants_review.txt"

# Historical tabs use minor spelling variants for a few categories.
ALIASES = {
    "misc": "Misc.",
    "miscellaneous": "Misc.",
    "food and dining": "Food & Dining",
    "dining": "Food & Dining",
    "alcohol": "Alcohol",
    "transportation": "Transport",
    "grocery": "Groceries",
    "payment": "Payments",
    "productivity": "Productivity Tooling",
    "productivity tools": "Productivity Tooling",
    "productivity tool": "Productivity Tooling",
    "income ": "Income",
    "credit card payment": "Payments",
    "clothing": "Shopping",
    "eyecare": "Health",
    "hair": "Haircut",
    "rental car & taxi": "Transport",
    "taxi": "Transport",
    "rent & utilities": "Utilities",
}


def build_category_mapper(categories):
    canon = {c.lower(): c for c in categories}

    def mapper(raw) -> Optional[str]:
        k = str(raw).strip().lower()
        if k in canon:
            return canon[k]
        return ALIASES.get(k)

    return mapper


def collect_votes(workbook: Path, exclude=()):
    map_cat = build_category_mapper(load_categories())
    sheets = pd.read_excel(workbook, sheet_name=None, engine="openpyxl")
    exclude = set(exclude)

    votes: Dict[str, Counter] = defaultdict(Counter)
    used_rows = 0
    sheets_used = 0
    unmapped = Counter()

    for name, df in sheets.items():
        if name in exclude:
            continue
        cols = {str(c).strip(): c for c in df.columns}
        if "Description" not in cols or "Category" not in cols:
            continue
        sheets_used += 1
        sub = df[[cols["Description"], cols["Category"]]].dropna()
        sub.columns = ["Description", "Category"]
        for _, row in sub.iterrows():
            cat = map_cat(row["Category"])
            if cat is None:
                unmapped[str(row["Category"]).strip()] += 1
                continue
            key = merchant_key(row["Description"])
            if not key:
                continue
            votes[key][cat] += 1
            used_rows += 1

    return votes, used_rows, sheets_used, unmapped


def resolve_rules(votes):
    rules = {}
    ambiguous = []
    for key, counter in votes.items():
        winner, n = counter.most_common(1)[0]
        total = sum(counter.values())
        rules[key] = winner
        if n / total < 0.8 and total >= 3:
            ambiguous.append((key, total, dict(counter)))
    return rules, ambiguous


def write_yaml(rules):
    header = (
        "# Merchant -> category lookup. Auto-generated by bootstrap_merchants.py\n"
        "# from historical categorized tabs, then freely hand-editable.\n"
        "#\n"
        "# Keys are stable merchant keys (see pipeline/text.py::merchant_key). At\n"
        "# runtime, the LONGEST key that is contained in a transaction's merchant\n"
        "# key wins. Add or correct a line and it takes effect on the next run.\n\n"
    )
    body = yaml.safe_dump(
        {"rules": dict(sorted(rules.items()))},
        sort_keys=False,
        allow_unicode=True,
        default_flow_style=False,
        width=1000,
    )
    OUT_PATH.write_text(header + body, encoding="utf-8")


def write_report(used_rows, sheets_used, n_keys, ambiguous, unmapped):
    lines = [
        "merchants.yaml bootstrap review",
        "================================",
        f"sheets used:        {sheets_used}",
        f"rows voted:         {used_rows}",
        f"distinct merchants: {n_keys}",
        "",
        "Ambiguous keys (winning category < 80% of votes, >=3 samples):",
    ]
    if ambiguous:
        for key, total, counter in sorted(ambiguous, key=lambda x: -x[1]):
            lines.append(f"  {key!r} ({total} votes): {counter}")
    else:
        lines.append("  (none)")
    lines += ["", "Unmapped category labels (skipped — fix in categories.yaml/ALIASES if real):"]
    if unmapped:
        for label, n in unmapped.most_common():
            lines.append(f"  {label!r}: {n}")
    else:
        lines.append("  (none)")
    REPORT_PATH.write_text("\n".join(lines) + "\n", encoding="utf-8")
    return lines


def main(argv):
    workbook = Path(argv[1]) if len(argv) > 1 else DEFAULT_WORKBOOK
    print(f"Reading {workbook}")
    votes, used_rows, sheets_used, unmapped = collect_votes(workbook)
    rules, ambiguous = resolve_rules(votes)
    write_yaml(rules)
    report = write_report(used_rows, sheets_used, len(rules), ambiguous, unmapped)
    print("\n".join(report))
    print(f"\nWrote {OUT_PATH.relative_to(ROOT)} ({len(rules)} rules)")
    print(f"Wrote {REPORT_PATH.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv))
